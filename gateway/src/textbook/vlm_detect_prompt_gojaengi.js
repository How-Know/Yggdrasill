// 고쟁이 문항 판독 프롬프트.
//
// 고쟁이는 쎈과 같은 문제집이지만 한 중단원이 세 단계가 아니라 네 단계이고,
// 문항 번호가 소단원마다 리셋되는 대신 책 전체를 관통하는 세 자리 연속 번호다.
// 쎈/RPM 공용 프롬프트(4자리 번호 + A 파트 가로 띠 조판 전제)를 그대로 쓸 수
// 없어서 전용 빌더로 분리했다.
//
//   A core_type      STEP1 핵심 유형    "핵심 NN"(주황) / "발전 NN"(보라) 배지
//   B advanced_type   STEP2 심화 유형    "유형 NN"(빨강) 배지, 끝에 서술형 묶음
//   C top_type        STEP3 최고난도 유형 유형 배지 없음
//   D creative_type   창의융합 유형      문항마다 "창의융합 ❶ <유형명>" 배지
//   E mid_unit_test   워크북 중단원 TEST  번호가 01 부터 재시작
//   F big_unit_test   워크북 대단원 TEST  번호가 01 부터 재시작

// 고쟁이 라벨 집합.
//   상          — 문항 번호 오른쪽 위의 별표(*). 그 단계 안에서 더 어려운 문항.
//   대표 문제    — STEP1/STEP2 유형의 첫 문항에 붙는 둥근 테두리 배지.
//   서술형       — STEP2 끝의 "서술형  풀이 과정을 쓰고 답을 구하시오." 묶음.
//   스키마       — STEP2 문항 중 앞쪽 스키마 해설 지면과 짝지어진 문항의 분홍 배지.
// 별표는 다른 배지와 겹칠 수 있어 "+" 로 이어 붙인 조합도 함께 허용한다.
export const GOJAENGI_LABELS = Object.freeze([
  '상',
  '대표 문제',
  '서술형',
  '스키마',
  '상+스키마',
  '서술형+상',
]);

