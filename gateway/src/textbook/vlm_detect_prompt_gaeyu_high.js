// 개념+유형 고등 문항 판독 프롬프트.
//
// 중등 개념+유형과 이름만 같고 지면 구성은 고등 개념원리에 가깝다. 소단원 하나가
//   개념 지면(개념 Plus, 개념 Check) → 필수예제 지면(한 쪽에 예제 하나 + 아래 "문제")
//   → … → 연습문제
// 순서로 이어진다. 코너가 넷뿐이고 지면마다 머리말이 분명해서 중등 빌더의
// 배지 판별 규칙(개념 확인 원형 배지, 쏙쏙/탄탄 STEP 이어받기)은 쓰지 않는다.
//
//   A high_concept_check  개념 Check  번호 1, 2, 3 … 개념 블록마다 1부터 다시
//   B high_example        필수예제    "필수예제 01" 배지, 소단원마다 01부터
//   C high_problem        문제        "01-1", "01-2" (필수예제 번호-순번)
//   D high_exercise       연습문제    1 … N, 소단원 끝. "실력" 구간이 뒤에 붙는다
//
// 개념 Check 는 블록마다 번호가 겹치므로 매니저앱이 블록 시작 쪽을 붙여
// "8-1" 로 저장한다. 모델은 인쇄된 숫자만 읽는다.

